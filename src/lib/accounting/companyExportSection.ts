/**
 * Company workspace export — accounting section (same-org; no bank ciphertext).
 */
import prisma from "@/lib/prisma";
import { toApiString } from "@/lib/accounting/money";

export async function buildAccountingExport(orgId: string) {
  const [
    settings,
    accounts,
    periods,
    entries,
    suppliers,
    bills,
    payments,
    expenses,
    bankAccounts,
    bankTxns,
    reconciliations,
    movements,
    taxCodes,
    mappings,
  ] = await Promise.all([
    prisma.accountingSettings.findUnique({ where: { orgId } }),
    prisma.ledgerAccount.findMany({
      where: { orgId },
      select: {
        id: true,
        code: true,
        name: true,
        type: true,
        subtype: true,
        systemKey: true,
        isHeader: true,
        isActive: true,
        locationId: true,
        cashFlowCategory: true,
        allowManualPosting: true,
      },
      orderBy: { code: "asc" },
      take: 5000,
    }),
    prisma.accountingPeriod.findMany({
      where: { orgId },
      orderBy: [{ fiscalYear: "asc" }, { periodNumber: "asc" }],
      take: 500,
    }),
    prisma.journalEntry.findMany({
      where: { orgId, status: { in: ["posted", "reversed"] } },
      include: {
        lines: {
          select: {
            lineNo: true,
            ledgerAccountId: true,
            locationId: true,
            debit: true,
            credit: true,
            description: true,
            partyType: true,
            guestProfileId: true,
            bookingAccountId: true,
            customerUserId: true,
            supplierId: true,
          },
          orderBy: { lineNo: "asc" },
        },
      },
      orderBy: { entryDate: "asc" },
      take: 10_000,
    }),
    prisma.supplier.findMany({
      where: { orgId },
      select: {
        id: true,
        code: true,
        name: true,
        email: true,
        phone: true,
        taxId: true,
        currency: true,
        isActive: true,
        bankName: true,
        bankAccountName: true,
        bankAccountLast4: true,
        // Never export bankAccountCiphertext
        locationId: true,
        archivedAt: true,
      },
      take: 5000,
    }),
    prisma.supplierBill.findMany({
      where: { orgId },
      select: {
        id: true,
        number: true,
        status: true,
        billDate: true,
        dueDate: true,
        total: true,
        amountPaid: true,
        amountDue: true,
        supplierId: true,
        currency: true,
      },
      take: 10_000,
    }),
    prisma.supplierPayment.findMany({
      where: { orgId },
      select: {
        id: true,
        number: true,
        status: true,
        paymentDate: true,
        amount: true,
        method: true,
        supplierId: true,
        currency: true,
      },
      take: 10_000,
    }),
    prisma.expense.findMany({
      where: { orgId },
      select: {
        id: true,
        number: true,
        status: true,
        expenseDate: true,
        amount: true,
        description: true,
        categoryId: true,
        paymentMode: true,
        currency: true,
      },
      take: 10_000,
    }),
    prisma.bankAccount.findMany({
      where: { orgId },
      select: {
        id: true,
        name: true,
        kind: true,
        currency: true,
        accountLast4: true,
        bankName: true,
        isDefault: true,
        isActive: true,
        locationId: true,
        openingBalance: true,
      },
      take: 500,
    }),
    prisma.bankTransaction.findMany({
      where: { orgId },
      select: {
        id: true,
        bankAccountId: true,
        txnDate: true,
        description: true,
        reference: true,
        amount: true,
        status: true,
        source: true,
      },
      orderBy: { txnDate: "asc" },
      take: 20_000,
    }),
    prisma.bankReconciliation.findMany({
      where: { orgId },
      select: {
        id: true,
        number: true,
        bankAccountId: true,
        statementDate: true,
        statementEndingBalance: true,
        difference: true,
        status: true,
        completedAt: true,
      },
      take: 2000,
    }),
    prisma.inventoryMovement.findMany({
      where: { orgId },
      select: {
        id: true,
        locationId: true,
        posProductId: true,
        shopProductId: true,
        kind: true,
        qty: true,
        unitCost: true,
        totalCost: true,
        sourceType: true,
        sourceId: true,
        createdAt: true,
      },
      take: 20_000,
    }),
    prisma.taxCode.findMany({
      where: { orgId },
      select: {
        id: true,
        code: true,
        name: true,
        rate: true,
        kind: true,
        isActive: true,
        syncedFromTaxSettings: true,
      },
      take: 500,
    }),
    prisma.accountingMapping.findMany({
      where: { orgId },
      select: {
        id: true,
        kind: true,
        matchKey: true,
        ledgerAccountId: true,
        locationId: true,
      },
      take: 5000,
    }),
  ]);

  return {
    settings: settings
      ? {
          enabled: settings.enabled,
          enabledAt: settings.enabledAt?.toISOString() ?? null,
          baseCurrency: settings.baseCurrency,
          timezone: settings.timezone,
          fiscalYearStartMonth: settings.fiscalYearStartMonth,
          goLiveDate: settings.goLiveDate.toISOString(),
          bookingRevenueRecognition: settings.bookingRevenueRecognition,
          membershipRecognition: settings.membershipRecognition,
          defaultPaymentTermsDays: settings.defaultPaymentTermsDays,
          postShopOrders: settings.postShopOrders,
          postTailoringJobs: settings.postTailoringJobs,
          giftCardBreakageOnExpiry: settings.giftCardBreakageOnExpiry,
          statementFooter: settings.statementFooter,
        }
      : null,
    chartOfAccounts: accounts,
    periods: periods.map((p) => ({
      id: p.id,
      fiscalYear: p.fiscalYear,
      periodNumber: p.periodNumber,
      startsOn: p.startsOn.toISOString(),
      endsOn: p.endsOn.toISOString(),
      status: p.status,
    })),
    journalEntries: entries.map((e) => ({
      id: e.id,
      number: e.number,
      entryDate: e.entryDate.toISOString(),
      status: e.status,
      kind: e.kind,
      sourceType: e.sourceType,
      sourceId: e.sourceId,
      memo: e.memo,
      reference: e.reference,
      totalDebit: toApiString(e.totalDebit),
      totalCredit: toApiString(e.totalCredit),
      locationId: e.locationId,
      lines: e.lines.map((l) => ({
        lineNo: l.lineNo,
        ledgerAccountId: l.ledgerAccountId,
        locationId: l.locationId,
        debit: toApiString(l.debit),
        credit: toApiString(l.credit),
        description: l.description,
        partyType: l.partyType,
        guestProfileId: l.guestProfileId,
        bookingAccountId: l.bookingAccountId,
        customerUserId: l.customerUserId,
        supplierId: l.supplierId,
      })),
    })),
    suppliers: suppliers.map((s) => ({
      ...s,
      archivedAt: s.archivedAt?.toISOString() ?? null,
    })),
    bills: bills.map((b) => ({
      ...b,
      billDate: b.billDate.toISOString(),
      dueDate: b.dueDate.toISOString(),
      total: toApiString(b.total),
      amountPaid: toApiString(b.amountPaid),
      amountDue: toApiString(b.amountDue),
    })),
    supplierPayments: payments.map((p) => ({
      ...p,
      paymentDate: p.paymentDate.toISOString(),
      amount: toApiString(p.amount),
    })),
    expenses: expenses.map((e) => ({
      ...e,
      expenseDate: e.expenseDate.toISOString(),
      amount: toApiString(e.amount),
    })),
    bankAccounts: bankAccounts.map((b) => ({
      ...b,
      openingBalance: toApiString(b.openingBalance),
    })),
    bankTransactions: bankTxns.map((t) => ({
      ...t,
      txnDate: t.txnDate.toISOString(),
      amount: toApiString(t.amount),
    })),
    reconciliations: reconciliations.map((r) => ({
      ...r,
      statementDate: r.statementDate.toISOString(),
      statementEndingBalance: toApiString(r.statementEndingBalance),
      difference: toApiString(r.difference),
      completedAt: r.completedAt?.toISOString() ?? null,
    })),
    inventoryMovements: movements.map((m) => ({
      ...m,
      qty: toApiString(m.qty),
      unitCost: toApiString(m.unitCost),
      totalCost: toApiString(m.totalCost),
      createdAt: m.createdAt.toISOString(),
    })),
    taxCodes: taxCodes.map((t) => ({
      ...t,
      rate: toApiString(t.rate),
    })),
    mappings,
  };
}
